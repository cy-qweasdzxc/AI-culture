import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

test('管理端合成资料新增、审核、发布、检索、撤审和退出', async ({ page }, testInfo) => {
  const password = process.env.E2E_ADMIN_PASSWORD
  test.skip(!password, 'Set E2E_ADMIN_PASSWORD for an isolated test API; never use production credentials.')
  const id = `e2e-fiction-${testInfo.project.name}-${Date.now()}`
  const title = `合成E2E剧情夹具 · ${id}`
  const query = id.replaceAll('-', '')
  const content = `【合成测试剧情，不是文化史实】虚构茶馆挂着${query}，用于验证发布与撤审的工程流程。`
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/admin')
  await page.getByLabel('账号', { exact: true }).fill(process.env.E2E_ADMIN_USERNAME ?? 'admin')
  await page.getByLabel('密码', { exact: true }).fill(password!)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('管理后台')
  await page.getByRole('tab', { name: '文化资料' }).click()
  await page.getByLabel('条目 ID', { exact: true }).fill(id)
  await page.getByLabel('标题', { exact: true }).fill(title)
  await page.getByLabel('来源名称', { exact: true }).fill('E2E自有合成fixture，非真实文化来源')
  await page.getByLabel('来源 URL', { exact: true }).fill(`https://example.invalid/fixture/${id}`)
  await page.getByLabel('授权说明', { exact: true }).fill('自有合成测试文本，仅在隔离测试数据库验证')
  await page.getByRole('combobox', { name: /资料类型/ }).selectOption('fiction')
  await page.getByRole('textbox', { name: /^正文/ }).fill(content)
  await page.getByRole('button', { name: '保存为待审核', exact: true }).click()
  const article = page.locator('article').filter({ has: page.getByText(title, { exact: true }) })
  await expect(article.getByText('pending · v1', { exact: true })).toBeVisible()
  await expect(article.getByRole('button', { name: '发布索引', exact: true })).toBeDisabled()
  await page.getByLabel('审核人员', { exact: true }).fill('E2E合成fixture确认，非文化资料审核')
  await page.getByRole('checkbox', { name: '我已核对当前条目的正文、来源 URL 与授权说明。' }).check()
  await article.getByRole('button', { name: '通过审核', exact: true }).click()
  await expect(article.getByText('reviewed · v2', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('管理后台')
  await page.getByRole('tab', { name: '文化资料' }).click()
  await article.getByRole('button', { name: '发布索引', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('检索索引已发布。')
  await page.getByLabel('检索问题', { exact: true }).fill(query)
  await page.getByRole('button', { name: '测试检索', exact: true }).click()
  await expect(page.locator('ol').getByText(new RegExp(title))).toBeVisible()
  await article.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('textbox', { name: /^正文/ }).fill(`${content} 编辑后须重新确认，不可沿用旧索引。`)
  await page.getByRole('button', { name: '保存为待审核', exact: true }).click()
  await expect(article.getByText('pending · v3', { exact: true })).toBeVisible()
  await expect(article.getByRole('button', { name: '发布索引', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '测试检索', exact: true }).click()
  await expect(page.getByText('没有命中任何已审核证据。这是正常的拒答前提，不是检索故障。')).toBeVisible()
  await expect(page.locator('ol').getByText(new RegExp(title))).toHaveCount(0)
  const visualDirectory = resolve(process.cwd(), '../.cache/e2e-visual')
  mkdirSync(visualDirectory, { recursive: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: resolve(visualDirectory, `admin-${testInfo.project.name}.png`), animations: 'disabled' })
  await page.getByRole('button', { name: / · 退出$/ }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('管理后台登录')
  const response = await page.request.get('/api/admin/knowledge')
  expect(response.status()).toBe(401)
  expect(errors).toEqual([])
})
